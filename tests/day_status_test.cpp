static void require(bool result, const std::string &message) {
  if (!result) throw std::runtime_error(message);
}
bool controlBusy = false;
bool controlPending = false;
int activeControlKind = 0;
bool rebootPending = false;
int resetHours = 0;
int resetMin = 0;
bool traydisptoday[11] = {};
bool traydismtoday[11] = {};
bool trayAlertEna[11] = {};
static unsigned trayWrites = 0;
static bool savedDispensed[11] = {};
static bool savedSkipped[11] = {};
void persistTrayStatus(int tray) {
  require(tray >= 1 && tray <= 10, "Persistence targeted an invalid tray");
  savedDispensed[tray] = traydisptoday[tray];
  savedSkipped[tray] = traydismtoday[tray];
  ++trayWrites;
}
struct PreferencesStub {
  int statusDay = 0;
  unsigned reads = 0, writes = 0;
  bool open = false, readOnly = false;
  void begin(const char *name, bool readonly) {
    require(!open && std::string(name) == "appSettings", "Wrong day persistence transaction");
    open = true; readOnly = readonly;
  }
  int getInt(const char *key, int fallback) {
    require(open && readOnly && std::string(key) == "statusDay" && fallback == 0, "Wrong day read");
    ++reads; return statusDay;
  }
  void putInt(const char *key, int value) {
    require(open && !readOnly && std::string(key) == "statusDay", "Wrong day write");
    ++writes; statusDay = value;
  }
  void end() { require(open, "Unbalanced Preferences end"); open = false; }
} preferences;

// Generated by test-day-status.sh directly from the current Check_Alerts.ino.
