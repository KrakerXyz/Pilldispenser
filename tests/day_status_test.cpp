static tm date(int year, int month, int day, int hour, int minute) {
  tm value{};
  value.tm_year = year - 1900; value.tm_mon = month - 1; value.tm_mday = day;
  value.tm_hour = hour; value.tm_min = minute; value.tm_isdst = -1;
  require(mktime(&value) != time_t(-1), "Test date could not be normalized");
  return value;
}
static void seedStatuses() {
  traydisptoday[1] = true; traydismtoday[3] = true; traydisptoday[9] = true;
  trayAlertEna[1] = true; // Tray9 deliberately remains manual-only.
}
static void assertPreserved() {
  require(traydisptoday[1] && traydismtoday[3] && traydisptoday[9] && trayWrites == 0,
          "Existing daily statuses were unexpectedly cleared");
}
static void assertAllCleared(unsigned expectedWrites = 10) {
  for (int tray = 1; tray <= 10; ++tray)
    require(!traydisptoday[tray] && !traydismtoday[tray] &&
            !savedDispensed[tray] && !savedSkipped[tray], "Daily status was not reset and persisted");
  require(trayWrites == expectedWrites, "Day reset did not persist exactly ten trays");
}
static void initialMigration() {
  seedStatuses();
  require(reconcileDayStatus(date(2026, 11, 12, 8, 15)), "Initial day migration rejected");
  assertPreserved();
  require(preferences.statusDay == 20261112 && preferences.writes == 1 && preferences.reads == 1,
          "Initial day marker was not persisted once");
}
static void disabledScheduleManualStatusReset() {
  seedStatuses(); std::fill(std::begin(trayAlertEna), std::end(trayAlertEna), false);
  preferences.statusDay = 20261111;
  require(reconcileDayStatus(date(2026, 11, 12, 8, 15)), "New day reset rejected");
  assertAllCleared(); require(preferences.statusDay == 20261112, "New day marker mismatch");
}
static void invalidClock() {
  seedStatuses(); preferences.statusDay = 20261111;
  require(!reconcileDayStatus(date(1970, 1, 1, 0, 0)), "Epoch boot clock accepted");
  require(!reconcileDayStatus(date(2023, 12, 31, 23, 59)), "Pre-validity clock accepted");
  assertPreserved();
  require(preferences.reads == 0 && preferences.writes == 0, "Invalid clock touched stored day");
}
static void repeatedCallsDoNotEraseTodaysDispense() {
  seedStatuses(); preferences.statusDay = 20261111;
  require(reconcileDayStatus(date(2026, 11, 12, 0, 0)), "Boundary reset rejected");
  assertAllCleared(); traydisptoday[2] = true;
  for (int i = 0; i < 4; ++i)
    require(reconcileDayStatus(date(2026, 11, 12, 0, 0)), "Repeated boundary call rejected");
  require(reconcileDayStatus(date(2026, 11, 12, 12, 30)), "Same-day later call rejected");
  require(traydisptoday[2] && trayWrites == 10 && preferences.reads == 1 && preferences.writes == 1,
          "Repeated reconciliation erased today's status or rewrote marker");
}
static void restartWithinCurrentDayPreservesStatus() {
  seedStatuses(); preferences.statusDay = 20261112;
  require(reconcileDayStatus(date(2026, 11, 12, 0, 0)), "Same-day boot rejected");
  assertPreserved(); require(preferences.writes == 0, "Same-day boot rewrote status marker");
}
static void lateBootBeforeAndAfterReset() {
  seedStatuses(); resetHours = 6; resetMin = 30; preferences.statusDay = 20261111;
  require(reconcileDayStatus(date(2026, 11, 12, 6, 29)), "Pre-boundary logical day rejected");
  assertPreserved(); require(preferences.statusDay == 20261111 && preferences.writes == 0,
                            "Pre-boundary boot prematurely advanced day");
  require(reconcileDayStatus(date(2026, 11, 12, 6, 31)), "Missed boundary reconciliation rejected");
  assertAllCleared(); require(preferences.statusDay == 20261112, "Post-boundary marker mismatch");
}
static void lateBootAfterMultipleMissedDays() {
  seedStatuses(); preferences.statusDay = 20261109;
  require(reconcileDayStatus(date(2026, 11, 12, 11, 0)), "Late boot reset rejected");
  assertAllCleared(); require(preferences.statusDay == 20261112 && preferences.writes == 1,
                            "Late boot did not reconcile directly to present day");
}
static void yearBoundary() {
  seedStatuses(); resetHours = 6; resetMin = 30; preferences.statusDay = 20261231;
  require(reconcileDayStatus(date(2027, 1, 1, 1, 0)), "Previous-year logical day rejected");
  assertPreserved(); require(preferences.statusDay == 20261231, "Year rollover normalized incorrectly");
  require(reconcileDayStatus(date(2027, 1, 1, 6, 30)), "New-year boundary rejected");
  assertAllCleared(); require(preferences.statusDay == 20270101, "New-year marker mismatch");
}
static void leapDayBoundary() {
  seedStatuses(); resetHours = 6; preferences.statusDay = 20240229;
  require(reconcileDayStatus(date(2024, 3, 1, 1, 0)), "Leap-day logical date rejected");
  assertPreserved(); require(preferences.statusDay == 20240229, "Leap-day normalization mismatch");
  require(reconcileDayStatus(date(2024, 3, 1, 6, 0)), "March boundary rejected");
  assertAllCleared(); require(preferences.statusDay == 20240301, "March marker mismatch");
}
static void busyDefersBoundary() {
  seedStatuses(); preferences.statusDay = 20261111; controlBusy = true; activeControlKind = 1;
  require(!reconcileDayStatus(date(2026, 11, 12, 8, 15)), "Busy boundary reset accepted");
  assertPreserved(); require(preferences.writes == 0, "Busy reset changed day marker");
  controlBusy = false; activeControlKind = 0;
  require(reconcileDayStatus(date(2026, 11, 12, 8, 16)), "Deferred reset did not resume");
  assertAllCleared(); require(preferences.statusDay == 20261112, "Deferred marker mismatch");
}
static void busyDefersMigration() {
  seedStatuses(); controlBusy = true; activeControlKind = 1;
  require(!reconcileDayStatus(date(2026, 11, 12, 8, 15)), "Busy initial migration accepted");
  assertPreserved(); require(preferences.writes == 0, "Busy migration wrote marker");
  controlBusy = false; activeControlKind = 0;
  require(reconcileDayStatus(date(2026, 11, 12, 8, 16)), "Deferred migration did not resume");
  assertPreserved(); require(preferences.statusDay == 20261112, "Deferred migration marker mismatch");
}
static void rebootReservationDefersAllReconciliation() {
  seedStatuses(); preferences.statusDay = 20261111; rebootPending = true;
  require(!reconcileDayStatus(date(2026, 11, 12, 8, 15)), "Reboot reservation allowed day mutation");
  assertPreserved(); require(preferences.reads == 0 && preferences.writes == 0,
                            "Reserved reboot touched persistence");
}
static void queuedCommandReconcilesBeforeMotion() {
  seedStatuses(); preferences.statusDay = 20261111;
  controlBusy = true; controlPending = true; activeControlKind = 0;
  require(reconcileDayStatus(date(2026, 11, 12, 0, 0)), "Queued unstarted command blocked day reset");
  assertAllCleared(); require(preferences.statusDay == 20261112, "Queued-command day marker mismatch");
  require(controlBusy && controlPending && activeControlKind == 0,
          "Day reconciliation consumed or released the motor command");
}

int main(int argc, char **argv) {
  if (argc != 2) return 2;
  setenv("TZ", "UTC0", 1); tzset();
  const std::string name = argv[1];
  try {
    if (name == "migration") initialMigration();
    else if (name == "manual-reset") disabledScheduleManualStatusReset();
    else if (name == "invalid-clock") invalidClock();
    else if (name == "repeat") repeatedCallsDoNotEraseTodaysDispense();
    else if (name == "same-day-boot") restartWithinCurrentDayPreservesStatus();
    else if (name == "reset-boundary") lateBootBeforeAndAfterReset();
    else if (name == "late-boot") lateBootAfterMultipleMissedDays();
    else if (name == "year-boundary") yearBoundary();
    else if (name == "leap-day") leapDayBoundary();
    else if (name == "busy-reset") busyDefersBoundary();
    else if (name == "busy-migration") busyDefersMigration();
    else if (name == "reboot-pending") rebootReservationDefersAllReconciliation();
    else if (name == "queued-command") queuedCommandReconcilesBeforeMotion();
    else throw std::runtime_error("Unknown case");
    require(!preferences.open, "Unclosed Preferences transaction");
    std::cout << "PASS day status: " << name << '\n';
  } catch (const std::exception &error) {
    std::cerr << "FAIL day status: " << name << ": " << error.what() << '\n'; return 1;
  }
}
